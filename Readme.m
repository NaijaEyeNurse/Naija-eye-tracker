# Naija Eye Tracker
Preventing loss to follow-up for eye patients in low-resource clinics.

## Problem I saw
- At 2 Division Eye Clinic Ibadan: 80+ patients/month arrive late, already blind
- Nov 2025 outreach Boripe PHC: 400 screened, 72 referred to LUTH, only 31 started treatment
- June 2026 Shao: 350 screened, 89 could not be traced

Current system: paper records. No tracking.

## What I am building
A simple follow-up records system for primary-care nurses:
- Register patient, record visual acuity and red flags
- Generate referral
- Track: Referred → Contacted → Attended → Lost
- Dashboard showing who is lost

Not a diagnostic device. Supports WHO Primary Eye Care referral protocol.

